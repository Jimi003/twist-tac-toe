"""Regenerates duel-table.js: the exact value of every Duel Tic-Tac-Toe position.

Each round both players pick a square at once. Different squares: both marks land.
Same square: a three-way split (X takes it / O takes it / tie, nothing changes).
Values are from X's point of view in [-1, 1], stored as int8 (value * 127), indexed by
sum(board[i] * 3**i) with board cells 0 = empty, 1 = X, 2 = O.

Usage: pip install scipy numpy && python3 tools/gen_duel_table.py
"""
import base64, os, sys
import numpy as np
from scipy.optimize import linprog

LINES = [(0,1,2),(3,4,5),(6,7,8),(0,3,6),(1,4,7),(2,5,8),(0,4,8),(2,4,6)]

def lines(b):
    return (any(b[i] == 1 and b[j] == 1 and b[k] == 1 for i, j, k in LINES),
            any(b[i] == 2 and b[j] == 2 and b[k] == 2 for i, j, k in LINES))

def game_value(M):
    n, m = M.shape
    c = np.zeros(n + 1); c[-1] = -1
    A = np.hstack([-M.T, np.ones((m, 1))])
    Aeq = np.zeros((1, n + 1)); Aeq[0, :n] = 1
    r = linprog(c, A_ub=A, b_ub=np.zeros(m), A_eq=Aeq, b_eq=[1],
                bounds=[(0, None)] * n + [(None, None)], method='highs')
    return r.x[-1]

def terminal(b):
    x, o = lines(b)
    if x and o: return 0.0
    if x: return 1.0
    if o: return -1.0
    if 0 not in b: return 0.0
    return None

memo = {}
def V(b):
    t = terminal(b)
    if t is not None: return t
    if b in memo: return memo[b]
    empt = [i for i in range(9) if b[i] == 0]
    n = len(empt)
    def put(c, p):
        l = list(b); l[c] = p; return tuple(l)
    base = np.zeros((n, n)); diag = np.zeros(n)
    for i, a in enumerate(empt):
        for j, c in enumerate(empt):
            if i == j:
                diag[i] = (V(put(a, 1)) + V(put(a, 2))) / 3
            else:
                l = list(b); l[a] = 1; l[c] = 2; base[i, j] = V(tuple(l))
    # a tied clash leaves the position unchanged, so the value is a fixed point
    v = 0.0
    for _ in range(60):
        M = base.copy()
        for i in range(n): M[i, i] = diag[i] + v / 3
        nv = game_value(M)
        if abs(nv - v) < 1e-10: v = nv; break
        v = nv
    memo[b] = v
    return v

if __name__ == '__main__':
    sys.setrecursionlimit(10000)
    V((0,) * 9)
    table = bytearray(3 ** 9)
    for b, v in memo.items():
        table[sum(b[i] * 3 ** i for i in range(9))] = int(round(v * 127)) & 0xFF
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'duel-table.js')
    with open(out, 'w') as f:
        f.write('/* Generated by tools/gen_duel_table.py - do not edit. */\n')
        f.write('window.DUEL_TABLE = "' + base64.b64encode(bytes(table)).decode() + '";\n')
    print(f'{len(memo)} positions solved; start value {V((0,) * 9):+.4f}; wrote {out}')
